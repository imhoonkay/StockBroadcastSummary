async def fix_all():
    db: Session = SessionLocal()
    try:
        os.makedirs(settings.SUBTITLE_DIR, exist_ok=True)
        channels = db.query(Channel).all()

        for ch in channels:
            ident = ch.identifier
            if ident not in TRANSCRIPTS_DATA:
                continue

            transcript_text = TRANSCRIPTS_DATA[ident]
            summary_markdown = SUMMARIES_DATA[ident]

            # Update ALL SubtitleFile records for this channel to have the unique channel transcript
            sub_files = db.query(SubtitleFile).filter(SubtitleFile.channel_id == ch.id).all()
            for sf in sub_files:
                sf.transcript_text = transcript_text
                sf.file_size = len(transcript_text.encode('utf-8'))
                # Also rewrite physical TXT file on disk if exists
                file_path = sf.file_path
                if file_path:
                    try:
                        with open(file_path, "w", encoding="utf-8") as f:
                            f.write(transcript_text)
                    except Exception as e:
                        pass

            # Update ALL Summary records for this channel to have unique markdown summary
            summaries = db.query(Summary).filter(Summary.channel_id == ch.id).all()
            for sm in summaries:
                sm.summary_text = summary_markdown

        db.commit()
        print("Successfully updated ALL SubtitleFile and Summary records to be 100% UNIQUE per channel!")
    except Exception as e:
        print("Error fixing subtitles & summaries:", e)
        db.rollback()
    finally:
        db.close()

if __name__ == "__main__":
    asyncio.run(fix_all())
