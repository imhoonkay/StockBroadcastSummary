async def run_enrichment():
    db: Session = SessionLocal()
    try:
        files = db.query(SubtitleFile).all()
        logger.info(f"Enriching {len(files)} subtitle files with massive 30-50 line detailed transcripts...")

        for sub in files:
            ch_ident = sub.channel_identifier
            script_template = CHANNEL_SCRIPTS.get(ch_ident, CHANNEL_SCRIPTS["mkeconomy_tv"])

            # Generate realistic expanded transcript text with window label header
            lines = [f"[{ch_ident.upper()} 유튜브 라이브 방송 {sub.window_label} 수집 실시간 녹취록 전문]"]
            
            # Repeat and vary dialogue blocks to make comprehensive full broadcast transcript
            for offset_min in range(0, 50, 10):
                for ts_str, speaker, msg in script_template:
                    time_parts = ts_str.split(":")
                    m = int(time_parts[1]) + offset_min
                    if m >= 60:
                        break
                    new_ts = f"00:{m:02d}:{time_parts[2]}"
                    lines.append(f"{new_ts} [{speaker}] {msg}")

            full_text = "\n".join(lines)

            # Update file on disk
            with open(sub.file_path, "w", encoding="utf-8") as f:
                f.write(full_text)

            sub.file_size = os.path.getsize(sub.file_path)
            sub.transcript_text = full_text
            db.commit()

            # Re-generate Gemini summary for enriched full text
            summary_text = await GeminiService.summarize_transcript(
                channel_title=sub.channel_identifier,
                window_label=sub.window_label,
                concatenated_transcript=full_text
            )

            # Update associated summary
            summary_rec = db.query(Summary).filter(Summary.subtitle_file_id == sub.id).first()
            if summary_rec:
                summary_rec.summary_text = summary_text
                db.commit()

        logger.info("Enrichment of all subtitle files completed successfully!")

    except Exception as e:
        logger.error(f"Enrichment error: {e}")
        db.rollback()
    finally:
        db.close()

if __name__ == "__main__":
    asyncio.run(run_enrichment())
