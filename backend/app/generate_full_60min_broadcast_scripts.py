async def run_full_60min_generation():
    db: Session = SessionLocal()
    try:
        files = db.query(SubtitleFile).all()
        logger.info(f"Generating full 60-minute continuous TV broadcast scripts for {len(files)} entries...")

        for sub in files:
            ch_ident = sub.channel_identifier
            window = sub.window_label.split()[-1] # e.g. '23:00~24:00'

            slot_dict = FULL_60MIN_SCRIPTS.get(window, FULL_60MIN_SCRIPTS["23:00~24:00"])
            script_text = slot_dict.get(ch_ident, list(slot_dict.values())[0]).strip()

            # Save file
            with open(sub.file_path, "w", encoding="utf-8") as f:
                f.write(script_text)

            sub.file_size = os.path.getsize(sub.file_path)
            sub.transcript_text = script_text
            db.commit()

            # Generate Gemini summary
            summary_text = await GeminiService.summarize_transcript(
                channel_title=sub.channel_identifier,
                window_label=sub.window_label,
                concatenated_transcript=script_text
            )

            summary_rec = db.query(Summary).filter(Summary.subtitle_file_id == sub.id).first()
            if summary_rec:
                summary_rec.summary_text = summary_text
                db.commit()

            logger.info(f"Updated full 60-min script for Subtitle #{sub.id} ({sub.channel_identifier} - {sub.window_label}) -> Size: {sub.file_size} bytes")

        logger.info("Full 60-minute script generation completed successfully!")

    except Exception as e:
        logger.error(f"Error in 60-min script generation: {e}")
        db.rollback()
    finally:
        db.close()

if __name__ == "__main__":
    asyncio.run(run_full_60min_generation())
