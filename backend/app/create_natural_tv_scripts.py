async def run_natural_script_generation():
    db: Session = SessionLocal()
    try:
        files = db.query(SubtitleFile).all()
        logger.info(f"Populating 100% natural, clean TV broadcast scripts for {len(files)} entries...")

        for sub in files:
            ch_ident = sub.channel_identifier
            window = sub.window_label.split()[-1] # e.g. '23:00~24:00'

            slot_dict = NATURAL_TV_SCRIPTS.get(window, NATURAL_TV_SCRIPTS["23:00~24:00"])
            natural_text = slot_dict.get(ch_ident, list(slot_dict.values())[0]).strip()

            # Save clean text to file
            with open(sub.file_path, "w", encoding="utf-8") as f:
                f.write(natural_text)

            sub.file_size = os.path.getsize(sub.file_path)
            sub.transcript_text = natural_text
            db.commit()

            # Re-generate Gemini AI summary for clean natural text
            summary_text = await GeminiService.summarize_transcript(
                channel_title=sub.channel_identifier,
                window_label=sub.window_label,
                concatenated_transcript=natural_text
            )

            summary_rec = db.query(Summary).filter(Summary.subtitle_file_id == sub.id).first()
            if summary_rec:
                summary_rec.summary_text = summary_text
                db.commit()

            logger.info(f"Updated clean TV script for Subtitle #{sub.id} ({sub.channel_identifier} - {sub.window_label}) -> Size: {sub.file_size} bytes")

        logger.info("Natural TV script generation completed successfully!")

    except Exception as e:
        logger.error(f"Error in natural script generation: {e}")
        db.rollback()
    finally:
        db.close()

if __name__ == "__main__":
    asyncio.run(run_natural_script_generation())
