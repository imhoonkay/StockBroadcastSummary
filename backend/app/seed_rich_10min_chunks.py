async def seed_rich():
    db: Session = SessionLocal()
    try:
        # Wipe old buffer entries
        db.query(SubtitleBuffer).delete()
        db.commit()

        channels = db.query(Channel).filter(Channel.status == "on").all()
        window_label = "2026-08-05 02:00~03:00"

        for time_key, full_dialogue in RICH_10MIN_CHUNKS.items():
            dt_obj = datetime.strptime(f"2026-08-05 {time_key}:00", "%Y-%m-%d %H:%M:%S")
            for ch in channels:
                chunk_text = full_dialogue.replace("한국경제TV", ch.name)
                buf = SubtitleBuffer(
                    channel_id=ch.id,
                    channel_identifier=ch.identifier,
                    window_label=window_label,
                    chunk_text=chunk_text,
                    created_at=dt_obj
                )
                db.add(buf)

        db.commit()
        print(f"Seeded {len(RICH_10MIN_CHUNKS) * len(channels)} RICH 10-minute buffer entries successfully!")
    except Exception as e:
        print("Error seeding rich buffers:", e)
        db.rollback()
    finally:
        db.close()

if __name__ == "__main__":
    asyncio.run(seed_rich())
